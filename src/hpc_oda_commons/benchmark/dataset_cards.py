"""Dataset cards, generated so they can never go stale (#249).

A card says what a dataset is, where it comes from, how it is curated, what it holds, and
where it is used. Every line comes from something the repo already holds:

- the dataset's descriptor (``datasets/descriptors/<name>.yml``): its name, system,
  providers, DOI and landing page, papers, license, files, mapping and filter;
- its runtime card (``docs/benchmarking/datasets/<name>.card.json``), when it has one: the
  characterization of its table and the runtime benchmark window;
- the error ceilings (``docs/benchmarking/datasets/*.ceiling.json``);
- the bundled recipes under ``recipes/``;
- the committed leaderboard (``site/leaderboard/leaderboard.json``).

``tests/unit/test_dataset_cards.py`` regenerates the cards and fails when they differ from the
committed ones, so changing any of those sources without regenerating turns CI red.

A dataset of your own gets a card the same way (#255): point the generator at your
descriptors, your benchmark records, your recipes and your leaderboard.
"""

from __future__ import annotations

import json
import os
from collections.abc import Iterator, Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

from hpc_oda_commons.benchmark.leaderboard_display import (
    REPO_BLOB_URL,
    card_name,
    format_headroom,
    format_metric_value,
    format_target_label,
    model_title,
)
from hpc_oda_commons.benchmarking.cards import characterization_lines, window_lines
from hpc_oda_commons.datasets.descriptor import (
    Descriptor,
    bundled_descriptor_paths,
    load_descriptor,
)

CARDS_DIR = Path("docs/datasets/cards")
BENCHMARK_DIR = Path("docs/benchmarking/datasets")
LEADERBOARD_JSON = Path("site/leaderboard/leaderboard.json")
LEADERBOARD_URL = "https://natlabrockies.github.io/hpc-oda-commons/leaderboard/"
_TASK_NAMES = {
    "job-runtime-prediction": "job runtime",
    "job-power-prediction": "job power",
}
_NOTICE = (
    "> Generated by `hpc-oda datasets cards` from the dataset's descriptor, its runtime card, "
    "the error ceilings, the bundled recipes and the published leaderboard. Don't edit it by "
    "hand: `tests/unit/test_dataset_cards.py` fails when it differs from what the generator "
    "writes."
)
_OWN_NOTICE = (
    "> Generated by `hpc-oda datasets cards` from the dataset's descriptor, its runtime card, "
    "its error ceilings, its recipes and your leaderboard. Regenerate it rather than edit it."
)


# --- reading the sources -----------------------------------------------------------------


def _repo_root() -> Path:
    return Path(__file__).resolve().parents[3]


@dataclass(frozen=True)
class _Context:
    """What a set of cards is built from, and where it is written."""

    descriptors: Mapping[str, Descriptor]
    paths: Mapping[str, Path]
    out_dir: Path
    leaderboard_link: str
    bundled: bool

    def rel(self, path: Path) -> str:
        """A file as a link from a card in ``out_dir``."""
        return Path(os.path.relpath(path.resolve(), self.out_dir.resolve())).as_posix()

    def model_link(self, model_id: str) -> str:
        """A model's card: beside these cards in the repo, else on GitHub."""
        cards = _repo_root() / "docs" / "models" / card_name(model_id)
        if self.out_dir.resolve().is_relative_to(_repo_root()):
            return self.rel(cards)
        return f"{REPO_BLOB_URL}docs/models/{card_name(model_id)}"

    def title(self, name: str) -> str:
        """A dataset's title: its descriptor's systems, or its name."""
        descriptor = self.descriptors.get(name)
        return ", ".join(descriptor.systems) if descriptor and descriptor.systems else name


def _runtime_card(name: str, benchmark_dir: Path) -> dict[str, Any] | None:
    path = benchmark_dir / f"{name}.card.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else None


def _ceilings(benchmark_dir: Path) -> dict[tuple[str, str], dict[str, Any]]:
    """Each error ceiling by (dataset, target), matched on the file's own fields."""
    out: dict[tuple[str, str], dict[str, Any]] = {}
    for path in sorted(benchmark_dir.glob("*.ceiling.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        dataset = str(data.get("dataset_id") or path.name.split(".")[0]).split(".")[-1]
        out[(dataset, str(data.get("target_field") or "runtime_seconds"))] = data
    return out


def _bundled_recipes(dirs: Sequence[Path] = ()) -> dict[str, list[dict[str, Any]]]:
    """The recipes by the dataset they run on: the bundled ones, or those in ``dirs``."""
    roots = list(dirs) or [_repo_root() / "src" / "hpc_oda_commons" / "recipes"]
    found: dict[str, list[dict[str, Any]]] = {}
    for path in sorted(p for root in roots for p in Path(root).rglob("*.yml")):
        recipe = yaml.safe_load(path.read_text(encoding="utf-8"))
        if not isinstance(recipe, dict) or "recipe_id" not in recipe:
            continue
        block = recipe.get("dataset") or {}
        dataset = str(block.get("id", ""))
        targets = sorted({str(m.get("target")) for m in recipe.get("metrics") or []})
        found.setdefault(dataset, []).append(
            {
                "recipe_id": str(recipe["recipe_id"]),
                "path": path,
                "model": str((recipe.get("model") or {}).get("id", "")),
                "target": ", ".join(targets),
                "targets": targets,
                "method": str((recipe.get("split") or {}).get("method", "")),
                "window": _window_text(block),
            }
        )
    return found


def _window_text(block: Mapping[str, Any]) -> str:
    """What rows a recipe reads, from its declared window and required columns (#249)."""
    window = block.get("window") or {}
    if not window:
        text = "the whole table"
    else:
        how = "submitted" if window.get("by") == "submit" else "running or submitted"
        text = f"{window['start']} → {window['end']} (the jobs {how} then)"
    required = list(block.get("require_nonnull") or [])
    if required:
        text += ", jobs with " + ", ".join(f"`{c}`" for c in required)
    return text


def _source_key(descriptor: Descriptor) -> str | None:
    """What identifies a dataset's source: its DOI, or else its landing page."""
    citation = descriptor.citation or {}
    return citation.get("doi") or citation.get("url")


# --- writing a card ------------------------------------------------------------------------


def _bytes(n: Any) -> str:
    try:
        value = float(n)
    except (TypeError, ValueError):
        return "size unknown"
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if value < 1000 or unit == "TB":
            return f"{value:,.0f} {unit}" if unit == "B" else f"{value:,.1f} {unit}"
        value /= 1000
    return f"{value:,.1f} TB"


def _link_doi(doi: str) -> str:
    return f"[{doi}](https://doi.org/{doi})"


def _source(name: str, descriptor: Descriptor, siblings: list[str], ctx: _Context) -> Iterator[str]:
    citation = descriptor.citation or {}
    license_ = descriptor.license or {}
    yield "## Source"
    yield ""
    if descriptor.providers:
        yield f"- **Provided by:** {', '.join(descriptor.providers)}"
    yield f"- **DOI:** {_link_doi(citation['doi']) if citation.get('doi') else 'none'}"
    if citation.get("url"):
        yield f"- **Landing page:** <{citation['url']}>"
    for paper in citation.get("papers") or []:
        where = _link_doi(paper["doi"]) if paper.get("doi") else f"<{paper.get('url')}>"
        yield f"- **Paper:** {paper['title']}, {where}"
    if license_:
        terms = str(license_.get("spdx", "unstated"))
        if license_.get("gated"):
            terms += ", registration required"
        if license_.get("url"):
            terms += f" (<{license_['url']}>)"
        yield f"- **License:** {terms}"
    if siblings:
        links = ", ".join(f"[{ctx.descriptors[s].name}]({s}.md)" for s in siblings)
        yield f"- **Other datasets from this source:** {links}"


def _curation(name: str, descriptor: Descriptor, ctx: _Context) -> Iterator[str]:
    source = descriptor.source
    resources = list(source.get("resources") or [])
    total = sum(int(r.get("bytes") or 0) for r in resources)
    kind = str(source.get("kind", "?"))
    record = f" record {source['record']}" if source.get("record") else ""
    yield "## Curation"
    yield ""
    yield (
        f"- **Fetched:** {len(resources)} file{'s' if len(resources) != 1 else ''} via "
        f"`{kind}`{record}, {_bytes(total) if total else 'size unknown'}"
        + (" (download by hand: the source needs registration)" if kind == "manual" else "")
    )
    for resource in resources:
        size = f", {_bytes(resource['bytes'])}" if resource.get("bytes") else ""
        yield f"    - `{resource.get('filename')}`{size}"
    for target in descriptor.targets:
        yield f"- **Prepared table:** `{target.output_path}` (`{target.schema}`)"
        targets = ", ".join(f"`{c}` ({format_target_label(c)})" for c in target.target_columns)
        yield f"- **Targets:** {targets or 'none'}"
        kept = target.filter or {}
        rules = "; ".join(f"`{k}`: {json.dumps(v)}" for k, v in kept.items())
        yield f"- **Rows kept:** {rules or 'all'}"
        columns = ", ".join(f"`{c}`" for c in target.mapping)
        yield f"- **Columns:** {columns}"
    path = ctx.paths[name]
    yield f"- **Descriptor:** [`{path.name}`]({ctx.rel(path)})"


def _characterization(card: Mapping[str, Any] | None) -> Iterator[str]:
    yield "## Characterization"
    yield ""
    if card is None:
        yield (
            "Not characterized: the dataset has no runtime card (`hpc-oda datasets characterize`)."
        )
        return
    yield from characterization_lines(dict(card))


def _results(name: str, table: Mapping[str, Any], ctx: _Context) -> Iterator[str]:
    rows = [r for r in table["rows"] if name in r["cells"]]
    rows.sort(
        key=lambda r: (
            r["cells"][name].get("headroom") is None,
            -(r["cells"][name].get("headroom") or 0.0),
            r["cells"][name]["mae"],
        )
    )
    if not rows:
        yield "Nothing has run on it yet."
        return
    yield "| Model | Headroom | MAE |"
    yield "|---|---:|---:|"
    for row in rows:
        cell = row["cells"][name]
        headroom = "—" if cell.get("headroom") is None else format_headroom(cell["headroom"])
        mae = format_metric_value("mae", float(cell["mae"]), target=table["target"])
        model = f"[{model_title(row['model'])}]({ctx.model_link(row['model'])})"
        yield f"| {model} | {headroom} | {mae} |"


def _benchmarks(
    name: str,
    card: Mapping[str, Any] | None,
    leaderboard: Mapping[str, Any],
    ceilings: Mapping[tuple[str, str], Mapping[str, Any]],
    recipes: list[dict[str, Any]],
    ctx: _Context,
) -> Iterator[str]:
    from hpc_oda_commons.benchmarking.hpc.matrix import MAX_NODE_ROWS

    tables = [t for t in leaderboard.get("tables", []) if name in t.get("roster", [])]
    when = str(leaderboard.get("generated_at", ""))[:10]
    yield "## On the leaderboard"
    yield ""
    if not tables:
        yield f"Not on the [leaderboard]({ctx.leaderboard_link}) of {when}."
    else:
        yield (
            f"From the [leaderboard]({ctx.leaderboard_link}) of {when}. Headroom is the share of "
            "the "
            "error between the window mean and the dataset's error ceiling that a model "
            "removes; the leaderboard explains it."
        )
    runtime_listed = any(t["target"] == "runtime_seconds" for t in tables)
    if card is not None and not runtime_listed:
        rows = int(card["benchmark_window"].get("n_rows") or 0)
        yield ""
        yield "### Job runtime"
        yield ""
        reason = (
            f"its window holds {rows:,} rows, more than one node takes ({MAX_NODE_ROWS:,})"
            if rows > MAX_NODE_ROWS
            else "nothing has run on its window"
        )
        yield f"It has a runtime window, but isn't on the runtime leaderboard: {reason}."
        yield ""
        yield from window_lines(dict(card))
    for table in tables:
        target = table["target"]
        yield ""
        yield f"### {table['title']}"
        yield ""
        yield str(table.get("caption") or "")
        if target == "runtime_seconds" and card is not None:
            yield ""
            yield "Its runtime window, from its runtime card:"
            yield ""
            yield from window_lines(dict(card))
        reads = sorted(
            {r["window"] for r in recipes if target in r["targets"] and r["method"] == "rolling"}
        )
        if target != "runtime_seconds" and reads:
            yield ""
            yield (f"Reads, as its recipes declare: {'; '.join(reads)}.")
        ceiling = ceilings.get((name, target))
        if ceiling is not None:
            floor = format_metric_value("mae", float(ceiling["floor"]["mae"]), target=target)
            yield ""
            yield (
                f"Error ceiling: an MAE floor of {floor} over {int(ceiling['scored_rows']):,} "
                "scored jobs."
            )
        note = (table.get("dataset_notes") or {}).get(name)
        if note:
            yield ""
            yield f"Note: {note}"
        yield ""
        yield from _results(name, table, ctx)


def _recipes(recipes: list[dict[str, Any]], ctx: _Context) -> Iterator[str]:
    yield "## Bundled recipes" if ctx.bundled else "## Recipes"
    yield ""
    if not recipes:
        yield "None."
        return
    yield "| Recipe | Model | Target | Split | Reads |"
    yield "|---|---|---|---|---|"
    for r in recipes:
        yield (
            f"| [`{r['recipe_id']}`]({ctx.rel(r['path'])}) | {model_title(r['model'])} "
            f"| `{r['target']}` | `{r['method']}` | {r['window']} |"
        )


def _serves(descriptor: Descriptor) -> str:
    return " and ".join(_TASK_NAMES.get(d, d) for d in descriptor.problem_domains) or "no task"


def render_dataset_card(
    name: str,
    *,
    leaderboard: Mapping[str, Any],
    card: Mapping[str, Any] | None,
    ceilings: Mapping[tuple[str, str], Mapping[str, Any]],
    recipes: list[dict[str, Any]],
    siblings: list[str],
    ctx: _Context,
) -> str:
    """One dataset's card, as Markdown."""
    descriptor = ctx.descriptors[name]
    lines = [
        f"# {descriptor.name}",
        "",
        f"`{descriptor.dataset_id}` · version {descriptor.version} · system "
        f"{ctx.title(name)} · serves {_serves(descriptor)}",
        "",
        _NOTICE if ctx.bundled else _OWN_NOTICE,
        "",
        " ".join(descriptor.description.split()),
        "",
        *_source(name, descriptor, siblings, ctx),
        "",
        *_curation(name, descriptor, ctx),
        "",
        *_characterization(card),
        "",
        *_benchmarks(name, card, leaderboard, ceilings, recipes, ctx),
        "",
        *_recipes(recipes, ctx),
    ]
    text = "\n".join(lines)
    while "\n\n\n" in text:
        text = text.replace("\n\n\n", "\n\n")
    return text.rstrip("\n") + "\n"


def render_index(leaderboard: Mapping[str, Any], ctx: _Context) -> str:
    """``README.md`` beside the cards: every dataset, linked to its card."""
    lines = [
        "# Datasets",
        "",
        _NOTICE if ctx.bundled else _OWN_NOTICE,
        "",
        "Each dataset's card. Where models stand on them: the "
        f"[leaderboard]({ctx.leaderboard_link}).",
        "",
        "| Dataset | System | Serves | Source | On the leaderboard |",
        "|---|---|---|---|---|",
    ]
    for name, descriptor in sorted(ctx.descriptors.items(), key=lambda kv: kv[1].name):
        citation = descriptor.citation or {}
        source = (
            _link_doi(citation["doi"])
            if citation.get("doi")
            else (f"[landing page]({citation['url']})" if citation.get("url") else "—")
        )
        tables = [t["title"] for t in leaderboard.get("tables", []) if name in t.get("roster", [])]
        lines.append(
            f"| [{descriptor.name}]({name}.md) | {ctx.title(name)} | "
            f"{_serves(descriptor)} | {source} | {', '.join(tables) or '—'} |"
        )
    return "\n".join(lines) + "\n"


def dataset_cards(
    leaderboard_path: Path = LEADERBOARD_JSON,
    benchmark_dir: Path = BENCHMARK_DIR,
    *,
    descriptors_dir: Path | None = None,
    recipe_dirs: Sequence[Path] = (),
    out_dir: Path = CARDS_DIR,
) -> dict[str, str]:
    """Every card, by file name, from the descriptors, the benchmark records, the recipes
    and the leaderboard.

    By default these are the bundled datasets, written into the repo. ``descriptors_dir``
    cards the descriptors there instead, a dataset of your own among them (#255), with the
    recipes in ``recipe_dirs`` and links made relative to ``out_dir``.
    """
    root = _repo_root()
    leaderboard_path = root / leaderboard_path
    leaderboard = json.loads(leaderboard_path.read_text(encoding="utf-8"))
    benchmark_dir = root / benchmark_dir
    out_dir = root / out_dir
    if descriptors_dir is None:
        paths = bundled_descriptor_paths()
        link = LEADERBOARD_URL
    else:
        paths = {p.stem: p for p in sorted(Path(descriptors_dir).glob("*.yml"))}
        page = leaderboard_path.parent / "index.html"
        link = Path(os.path.relpath(page.resolve(), out_dir.resolve())).as_posix()
    descriptors = {name: load_descriptor(path) for name, path in paths.items()}
    ctx = _Context(descriptors, paths, out_dir, link, bundled=descriptors_dir is None)
    ceilings = _ceilings(benchmark_dir)
    recipes = _bundled_recipes(recipe_dirs)
    cards = {}
    for name, descriptor in descriptors.items():
        key = _source_key(descriptor)
        siblings = sorted(
            other
            for other, d in descriptors.items()
            if other != name and key is not None and _source_key(d) == key
        )
        cards[f"{name}.md"] = render_dataset_card(
            name,
            leaderboard=leaderboard,
            card=_runtime_card(name, benchmark_dir),
            ceilings=ceilings,
            recipes=recipes.get(name, []),
            siblings=siblings,
            ctx=ctx,
        )
    cards["README.md"] = render_index(leaderboard, ctx)
    return cards


def write_dataset_cards(
    out_dir: Path = CARDS_DIR,
    leaderboard_path: Path = LEADERBOARD_JSON,
    benchmark_dir: Path = BENCHMARK_DIR,
    *,
    descriptors_dir: Path | None = None,
    recipe_dirs: Sequence[Path] = (),
) -> list[Path]:
    """Write every card into ``out_dir``, removing cards of datasets no longer there."""
    out_dir.mkdir(parents=True, exist_ok=True)
    cards = dataset_cards(
        leaderboard_path,
        benchmark_dir,
        descriptors_dir=descriptors_dir,
        recipe_dirs=recipe_dirs,
        out_dir=out_dir,
    )
    for stale in out_dir.glob("*.md"):
        if stale.name not in cards:
            stale.unlink()
    written = []
    for name, text in cards.items():
        path = out_dir / name
        path.write_text(text, encoding="utf-8")
        written.append(path)
    return written
