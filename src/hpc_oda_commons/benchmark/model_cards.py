"""Model cards, generated from the code so they can never go stale (#247).

A card says what a model is, how it runs, what it reads, its settings, the bundled recipes
that run it, and where it stands on the published leaderboard. Every line comes from
something the repo already holds:

- the registry, built from ``models/<name>/model.yml`` and the recipes: the model's title,
  description and targets;
- ``benchmark.runner.RUNNERS``: the split methods it runs under, the recipe keys each
  runner reads (found by reading the runner's source), and the dataclass it configures;
- the bundled recipes under ``recipes/``;
- the committed leaderboard (``site/leaderboard/leaderboard.json``).

``tests/unit/test_model_cards.py`` regenerates the cards and fails when they differ from the
committed ones, so changing any of those sources without regenerating turns CI red.
"""

from __future__ import annotations

import ast
import dataclasses
import inspect
import json
import sys
import textwrap
from collections.abc import Iterator, Mapping
from pathlib import Path
from typing import Any

import yaml

from hpc_oda_commons.benchmark.leaderboard_display import (
    card_name,
    dataset_doc,
    dataset_title,
    format_headroom,
    format_metric_value,
    model_titles,
)

CARDS_DIR = Path("docs/models")
LEADERBOARD_JSON = Path("site/leaderboard/leaderboard.json")
LEADERBOARD_URL = "https://natlabrockies.github.io/hpc-oda-commons/leaderboard/"
_FROM_CARD = "../.."  # docs/models/<card>.md back to the repo root
_TARGET_NAMES = {
    "job-runtime-prediction": "job runtime",
    "job-power-prediction": "job power",
}
_NOTICE = (
    "> Generated by `hpc-oda models cards` from the code, the registry, the bundled recipes "
    "and the published leaderboard. Don't edit it by hand: `tests/unit/test_model_cards.py` "
    "fails when it differs from what the generator writes."
)


# --- reading the sources -----------------------------------------------------------------


def _repo_root() -> Path:
    return Path(__file__).resolve().parents[3]


def _rel(path: Path) -> str:
    """A repo file as a link from a card."""
    return f"{_FROM_CARD}/{path.resolve().relative_to(_repo_root()).as_posix()}"


def _source_file(obj: Any) -> Path:
    return Path(inspect.getsourcefile(obj) or "")


def _format_value(value: Any) -> str:
    if isinstance(value, (frozenset, set)):
        value = sorted(value)
    if isinstance(value, tuple):
        value = list(value)
    if isinstance(value, str):
        return f"`{value}`" if value else '`""`'
    return f"`{value!r}`" if not isinstance(value, list) else f"`{json.dumps(value)}`"


def _default(field: dataclasses.Field) -> Any:
    if field.default is not dataclasses.MISSING:
        return field.default
    if field.default_factory is not dataclasses.MISSING:  # type: ignore[misc]
        return field.default_factory()  # type: ignore[misc]
    return dataclasses.MISSING


def _split_keys(run: Any, config: type | None) -> list[tuple[str, str]]:
    """The recipe ``split`` keys a runner reads, and their defaults, from its source.

    Follows the functions of the runner's module that it hands ``split`` to, such as the
    shared rolling-window helper, so a key read there counts too.
    """
    defaults = config() if config is not None and _constructible(config) else None
    keys: dict[str, str] = {}
    _collect_split_keys(run, defaults, keys, seen=set())
    return sorted(keys.items())


def _collect_split_keys(fn: Any, defaults: Any, keys: dict[str, str], seen: set[str]) -> None:
    if fn.__qualname__ in seen:
        return
    seen.add(fn.__qualname__)
    tree = ast.parse(textwrap.dedent(inspect.getsource(fn)))
    # Objects the function makes from a class it can see: ``model = SomeModel()``.
    instances: dict[str, type] = {}
    for node in ast.walk(tree):
        if (
            isinstance(node, ast.Assign)
            and len(node.targets) == 1
            and isinstance(node.targets[0], ast.Name)
            and isinstance(node.value, ast.Call)
            and isinstance(node.value.func, ast.Name)
            and inspect.isclass(fn.__globals__.get(node.value.func.id))
        ):
            instances[node.targets[0].id] = fn.__globals__[node.value.func.id]
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and _passes_split(node):
            helper = None
            if isinstance(node.func, ast.Name):
                helper = fn.__globals__.get(node.func.id)
            elif (
                isinstance(node.func, ast.Attribute)
                and isinstance(node.func.value, ast.Name)
                and node.func.value.id in instances
            ):
                helper = getattr(instances[node.func.value.id], node.func.attr, None)
            if inspect.isfunction(helper):
                _collect_split_keys(helper, defaults, keys, seen)
        key, default_node = None, None
        if (
            isinstance(node, ast.Call)
            and isinstance(node.func, ast.Attribute)
            and node.func.attr == "get"
            and isinstance(node.func.value, ast.Name)
            and node.func.value.id == "split"
            and node.args
            and isinstance(node.args[0], ast.Constant)
        ):
            key = node.args[0].value
            default_node = node.args[1] if len(node.args) > 1 else ast.Constant(None)
        elif (
            isinstance(node, ast.Subscript)
            and isinstance(node.value, ast.Name)
            and node.value.id == "split"
            and isinstance(node.slice, ast.Constant)
        ):
            key = node.slice.value
        if not isinstance(key, str) or key == "method":
            continue
        shown = _default_text(default_node, fn, defaults)
        if key not in keys or keys[key] == "required":
            keys[key] = shown


def _passes_split(call: ast.Call) -> bool:
    return any(isinstance(a, ast.Name) and a.id == "split" for a in call.args) or any(
        isinstance(k.value, ast.Name) and k.value.id == "split" for k in call.keywords
    )


def _constructible(config: type) -> bool:
    return all(_default(f) is not dataclasses.MISSING for f in dataclasses.fields(config))


def _default_text(node: ast.expr | None, run: Any, defaults: Any) -> str:
    """A ``split.get`` default as a reader would want it: its value where it can be known."""
    if node is None:
        return "required"
    if isinstance(node, ast.Constant):
        return _format_value(node.value)
    if (
        isinstance(node, ast.Attribute)
        and isinstance(node.value, ast.Name)
        and node.value.id == "defaults"
        and defaults is not None
    ):
        return _format_value(getattr(defaults, node.attr))
    if (
        isinstance(node, ast.Attribute)
        and isinstance(node.value, ast.Name)
        and dataclasses.is_dataclass(run.__globals__.get(node.value.id))
    ):
        return _format_value(getattr(run.__globals__[node.value.id], node.attr))
    if isinstance(node, ast.Name) and node.id in run.__globals__:
        value = run.__globals__[node.id]
        if isinstance(value, (int, float, str, tuple, frozenset)):
            return _format_value(value)
    return f"`{ast.unparse(node)}`"


def _uses_allowlist(config: type | None) -> bool:
    """Whether the model selects features with the shared submit-time allowlist."""
    if config is None:
        return False
    for klass in config.__mro__:
        module = sys.modules.get(klass.__module__)
        if module is None or klass is object:
            continue
        if "feature_policy" in inspect.getsource(module):
            return True
    return False


def _bundled_recipes(model_id: str) -> list[dict[str, Any]]:
    root = _repo_root() / "src" / "hpc_oda_commons" / "recipes"
    found = []
    for path in sorted(root.rglob("*.yml")):
        recipe = yaml.safe_load(path.read_text(encoding="utf-8"))
        if not isinstance(recipe, dict) or (recipe.get("model") or {}).get("id") != model_id:
            continue
        targets = sorted({str(m.get("target")) for m in recipe.get("metrics") or []})
        found.append(
            {
                "recipe_id": str(recipe.get("recipe_id", path.stem)),
                "path": path,
                "target": ", ".join(targets),
                "method": str((recipe.get("split") or {}).get("method", "")),
                "dataset": str((recipe.get("dataset") or {}).get("id", "")),
            }
        )
    return found


# --- writing a card ------------------------------------------------------------------------


def _results(model_id: str, leaderboard: Mapping[str, Any]) -> Iterator[str]:
    tables = [
        t for t in leaderboard.get("tables", []) if any(r["model"] == model_id for r in t["rows"])
    ]
    yield "## Results"
    yield ""
    when = str(leaderboard.get("generated_at", ""))[:10]
    if not tables:
        yield f"Not on the [leaderboard]({LEADERBOARD_URL}) of {when}."
        return
    yield (
        f"From the [leaderboard]({LEADERBOARD_URL}) of {when}. Headroom is the share of the "
        "error between the window mean and the dataset's error ceiling that the model removes; "
        "the leaderboard explains it."
    )
    for table in tables:
        ranked = [r for r in table["rows"] if r["average"] is not None]
        row = next(r for r in table["rows"] if r["model"] == model_id)
        yield ""
        yield f"### {table['title']}"
        yield ""
        if row["average"] is not None:
            rank = ranked.index(row) + 1
            yield (
                f"Rank {rank} of {len(ranked)}, with an average headroom of "
                f"{format_headroom(row['average'])} over {len(table['roster'])} datasets."
            )
        else:
            yield f"Unranked: it ran on {row['datasets_run']} of {len(table['roster'])} datasets."
        yield ""
        yield "| Dataset | Headroom | MAE |"
        yield "|---|---:|---:|"
        for dataset in table["datasets"]:
            cell = row["cells"].get(dataset)
            if cell is None:
                continue
            headroom = "—" if cell.get("headroom") is None else format_headroom(cell["headroom"])
            mae = format_metric_value("mae", float(cell["mae"]), target=table["target"])
            title = dataset_title(dataset)
            doc = dataset_doc(dataset)
            name = f"[{title}](../../{doc})" if doc else title
            yield f"| {name} (`{dataset}`) | {headroom} | {mae} |"


def _how_it_runs(model_id: str, runners: Mapping[tuple[str, str], Any]) -> Iterator[str]:
    from hpc_oda_commons.benchmarking.hpc.matrix import LOOKBACK_ARMS, RUNTIME_MODELS

    yield "## How it runs"
    yield ""
    if model_id.removeprefix("model.") in RUNTIME_MODELS:
        arms = ", ".join(str(a) for a in LOOKBACK_ARMS)
        yield (
            f"It is in the runtime fleet (`bench-matrix`), at training lookbacks of {arms} days."
        )
        yield ""
    yield "`hpc-oda benchmark` runs it with these `split.method` values:"
    for (mid, method), spec in sorted(runners.items()):
        if mid != model_id:
            continue
        yield ""
        configured = f", configuring `{spec.config.__name__}`" if spec.config else ""
        yield f"### `{method}`"
        yield ""
        yield f"Runner: `{spec.run.__name__}`{configured}. The recipe `split` keys it reads:"
        yield ""
        keys = _split_keys(spec.run, spec.config)
        if not keys:
            yield "None beyond `method`."
            continue
        yield "| Key | Default |"
        yield "|---|---|"
        for key, default in keys:
            yield f"| `{key}` | {default} |"


def _inputs(model_id: str, runners: Mapping[tuple[str, str], Any]) -> Iterator[str]:
    from hpc_oda_commons.models.feature_policy import RUNTIME_PREDICTION_FEATURE_FIELDS

    configs = [s.config for (mid, _m), s in sorted(runners.items()) if mid == model_id]
    yield "## Inputs"
    yield ""
    if any(_uses_allowlist(c) for c in configs):
        policy = _source_file(sys.modules["hpc_oda_commons.models.feature_policy"])
        fields = ", ".join(f"`{f}`" for f in sorted(RUNTIME_PREDICTION_FEATURE_FIELDS))
        yield (
            "It selects features with the shared submit-time allowlist "
            f"([`feature_policy.py`]({_rel(policy)})): whichever of its columns a dataset has."
        )
        yield ""
        yield "<details><summary>The allowlist</summary>"
        yield ""
        yield f"{fields}"
        yield ""
        yield "</details>"
    else:
        yield "It does not use the shared submit-time allowlist."
    yield ""
    yield "It predicts the recipe's metric target."
    named = sorted(
        {
            (f.name, _format_value(_default(f)))
            for c in configs
            if c is not None
            for f in dataclasses.fields(c)
            if (f.name.endswith("_field") or f.name.endswith("_fields"))
            and f.name != "target_field"  # the recipe's metric target sets it
            and _default(f) is not dataclasses.MISSING
        }
    )
    if named:
        yield ""
        yield "Columns named in its settings:"
        yield ""
        for name, default in named:
            yield f"- `{name}`: {default}"


def _settings(model_id: str, runners: Mapping[tuple[str, str], Any]) -> Iterator[str]:
    configs = []
    for (mid, _method), spec in sorted(runners.items()):
        if mid == model_id and spec.config is not None and spec.config not in configs:
            configs.append(spec.config)
    if not configs:
        return
    yield "## Settings"
    for config in configs:
        yield ""
        yield f"`{config.__name__}` ([source]({_rel(_source_file(config))})), with its defaults:"
        yield ""
        yield "| Setting | Default |"
        yield "|---|---|"
        for field in dataclasses.fields(config):
            value = _default(field)
            shown = "required" if value is dataclasses.MISSING else _format_value(value)
            yield f"| `{field.name}` | {shown} |"


def _recipes(model_id: str) -> Iterator[str]:
    recipes = _bundled_recipes(model_id)
    yield "## Bundled recipes"
    yield ""
    if not recipes:
        yield "None."
        return
    yield "| Recipe | Target | Split | Dataset |"
    yield "|---|---|---|---|"
    for r in recipes:
        yield (
            f"| [`{r['recipe_id']}`]({_rel(r['path'])}) | `{r['target']}` | `{r['method']}` "
            f"| `{r['dataset']}` |"
        )


def render_model_card(
    entry: Any, leaderboard: Mapping[str, Any], runners: Mapping[tuple[str, str], Any]
) -> str:
    """One model's card, as Markdown."""
    module = sys.modules.get(entry.reference.module) if entry.reference else None
    if module is None and entry.reference is not None:
        import importlib

        module = importlib.import_module(entry.reference.module)
    targets = " and ".join(_TARGET_NAMES.get(d, d) for d in entry.problem_domain)
    lines = [
        f"# {entry.name}",
        "",
        f"`{entry.id}` · version {entry.version} · predicts {targets}",
        "",
        _NOTICE,
        "",
        entry.description,
        "",
        *_results(entry.id, leaderboard),
        "",
        *_how_it_runs(entry.id, runners),
        "",
        *_inputs(entry.id, runners),
        "",
        *_settings(entry.id, runners),
        "",
        *_recipes(entry.id),
        "",
        "## Source",
        "",
        f"[`{entry.reference.module}`]({_rel(_source_file(module))})" if module else "—",
    ]
    text = "\n".join(lines)
    while "\n\n\n" in text:
        text = text.replace("\n\n\n", "\n\n")
    return text.rstrip("\n") + "\n"


def render_index(entries: list[Any]) -> str:
    """``docs/models/README.md``: every model, linked to its card."""
    lines = [
        "# Models",
        "",
        _NOTICE,
        "",
        f"Each model's card. Where they stand: the [leaderboard]({LEADERBOARD_URL}).",
        "",
        "| Model | Id | Predicts |",
        "|---|---|---|",
    ]
    for entry in entries:
        targets = ", ".join(_TARGET_NAMES.get(d, d) for d in entry.problem_domain)
        lines.append(f"| [{entry.name}]({card_name(entry.id)}) | `{entry.id}` | {targets} |")
    return "\n".join(lines) + "\n"


def model_cards(leaderboard_path: Path = LEADERBOARD_JSON) -> dict[str, str]:
    """Every card, by file name, from the registry, the runners and the leaderboard."""
    from hpc_oda_commons.benchmark.runner import RUNNERS
    from hpc_oda_commons.registry.snapshot import load_registry_index

    leaderboard = json.loads(Path(leaderboard_path).read_text(encoding="utf-8"))
    entries = sorted(
        (e for e in load_registry_index().entries if e.entry_type == "model"),
        key=lambda e: e.name.lower(),
    )
    assert {e.id for e in entries} == set(model_titles())
    cards = {card_name(e.id): render_model_card(e, leaderboard, RUNNERS) for e in entries}
    cards["README.md"] = render_index(entries)
    return cards


def write_model_cards(
    out_dir: Path = CARDS_DIR, leaderboard_path: Path = LEADERBOARD_JSON
) -> list[Path]:
    """Write every card into ``out_dir``, removing cards of models no longer registered."""
    out_dir.mkdir(parents=True, exist_ok=True)
    cards = model_cards(leaderboard_path)
    for stale in out_dir.glob("*.md"):
        if stale.name not in cards:
            stale.unlink()
    written = []
    for name, text in cards.items():
        path = out_dir / name
        path.write_text(text, encoding="utf-8")
        written.append(path)
    return written
