"""The registry is built from the files that define each entry, so it can't drift (#249)."""

from __future__ import annotations

import importlib
import importlib.resources as ir
from pathlib import Path

import yaml

from hpc_oda_commons.benchmark.runner import RUNNERS
from hpc_oda_commons.registry.snapshot import load_registry_index

_PACKAGE = Path(str(ir.files("hpc_oda_commons")))


def _entries(entry_type: str) -> dict:
    return {e.id: e for e in load_registry_index().entries if e.entry_type == entry_type}


def test_every_model_package_and_runner_is_registered() -> None:
    packages = {p.parent.name for p in _PACKAGE.glob("models/*/model.py")}
    assert {f"model.{name}" for name in packages} == set(_entries("model"))
    assert {model_id for model_id, _method in RUNNERS} <= set(_entries("model"))


def test_every_reference_resolves_to_its_class() -> None:
    for entry in [*_entries("model").values(), *_entries("adapter").values()]:
        assert entry.reference is not None
        module = importlib.import_module(str(entry.reference.module))
        assert hasattr(module, str(entry.reference.object)), entry.id


def test_every_bundled_recipe_and_descriptor_is_registered() -> None:
    recipe_ids = set()
    for path in _PACKAGE.glob("recipes/**/*.yml"):
        payload = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        if "recipe_id" in payload:
            recipe_ids.add(payload["recipe_id"])
    assert recipe_ids == set(_entries("recipe"))
    assert len(_entries("dataset")) == len(list(_PACKAGE.glob("datasets/descriptors/*.yml")))


def test_a_models_tasks_come_from_the_recipes_that_run_it() -> None:
    models = _entries("model")
    # The runtime fleet's recipes are generated by the HPC matrix, not bundled.
    assert "job-runtime-prediction" in models["model.random_forest"].problem_domain
    # MLP is not on the power protocol; UoPC is power only.
    assert models["model.mlp"].problem_domain == ("job-runtime-prediction",)
    assert models["model.uopc"].problem_domain == ("job-power-prediction",)


def test_dependencies_come_from_imports() -> None:
    models = _entries("model")
    assert any(dep.startswith("xgboost") for dep in models["model.xgboost"].dependencies)
    assert not any(dep.startswith("xgboost") for dep in models["model.mlp"].dependencies)
